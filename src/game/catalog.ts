export function createDefaultCustomization(bike: MotorcycleSpecs): BikeCustomization {
  return {
    paintColor: bike.defaultColor,
    wheelFinish: bike.category === 'dirt' || bike.category === 'adventure' ? 'gold' : 'alloy',
    exhaustStyle: 'stock',
    headlightTint: 'warm',
    plateText: 'BA 24 PA 4812',
  };
}

export function createInitialSaveData(): SaveData {
  const customizations: Record<string, BikeCustomization> = {};
  for (const bike of MOTORCYCLES) {
    customizations[bike.id] = createDefaultCustomization(bike);
  }
  return {
    version: 2,
    moneyNpr: 15000,
    selectedBikeId: 'himalayan_411',
    ownedBikeIds: ['himalayan_411'],
    customizations,
    completedMissionIds: [],
    bestMissionTimes: {},
    discoveredLandmarkIds: ['ktm_garage', 'ktm_petrol', 'ktm_durbar'],
    totalStuntScore: 0,
    totalDistanceKm: 0,
    settings: { ...DEFAULT_SETTINGS },
  };
}
